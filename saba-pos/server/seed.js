/* ------------------------------------------------------------ demo --- */

/**
 * Build the worked example and write it down.
 *
 * The example itself is generated by `shared/worked-example.js`, which the
 * published demonstration also runs — so what a client is shown in a browser
 * and what a restaurant sees on its own first demonstration are the same
 * service, down to the paise. All this function does is persist it.
 */
function seedDemo() {
  log.info('building the worked example…');
  const started = Date.now();

  const staff = auth.listUsers();
  const manager = staff.find((u) => u.role === 'manager');
  const example = buildWorkedExample({
    today: store.today(),
    users: {
      manager,
      captain: staff.find((u) => u.role === 'captain') || manager,
      cashier: staff.find((u) => u.role === 'cashier') || manager,
    },
    uid: () => `pay_${randomUUID().slice(0, 12)}`,
  });

  tx(() => {
    for (const order of example.orders) insertOrder(order);
    for (const booking of example.reservations) {
      store.saveReservation(booking, { name: 'System' });
    }
    for (const { itemId, by, note } of example.eightySix) {
      store.setEightySix(itemId, true, { actor: by, note });
    }
    // The generator allocated its own numbers; the database has to agree, or
    // the next real bill would reuse one.
    for (const [name, value] of Object.entries(example.counters)) {
      run('INSERT INTO counters (name, value) VALUES (?, ?)'
        + ' ON CONFLICT (name) DO UPDATE SET value = excluded.value', name, value);
    }
    bumpRevision();
  });

  log.info('worked example ready', {
    bills: example.orders.length,
    bookings: example.reservations.length,
    ms: Date.now() - started,
  });
}

function insertOrder(order) {
  const totals = costOrder(order);
  run(
    'INSERT INTO orders (id, number, code, business_day, table_id, status, invoice_no,'
    + ' opened_at, closed_at, total_paise, covers, doc, updated_at)'
    + ' VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
    order.id, order.number, order.code, order.businessDay, order.tableId,
    order.status, order.invoice?.number ?? null, order.openedAt, order.closedAt ?? null,
    totals.total, order.covers, JSON.stringify(order), Date.now()
  );
}

/* ------------------------------------------------------------- reset --- */

/**
 * Wipe every order, booking and audit entry and rebuild the worked example.
 *
 * Staff accounts and the carte survive, because a demonstration that forgets
 * its own sign-in PINs halfway through is worse than one that does not reset.
 * The API refuses to call this unless the server was started in demo mode.
 */
export function resetDemo() {
  tx(() => {
    run('DELETE FROM orders');
    run('DELETE FROM reservations');
    run('DELETE FROM audit');
    run('DELETE FROM shifts');
    run('DELETE FROM eighty_six');
    run("DELETE FROM counters WHERE name IN ('order', 'invoice')");
    bumpRevision();
  });
  seedDemo();
}
